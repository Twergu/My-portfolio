"""Run pytest and derive report counts from JUnit XML, never from a constant."""

import hashlib
import json
import os
import subprocess
import sys
import xml.etree.ElementTree as ET
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    if os.getenv("RAG_REQUIRE_POSTGRES_TESTS") == "1" and not os.getenv("RAG_TEST_DATABASE_URL"):
        raise SystemExit("RAG_TEST_DATABASE_URL is required; PostgreSQL tests must not skip in CI.")
    reports = ROOT / "reports"
    reports.mkdir(exist_ok=True)
    results = ROOT / "test-results"
    results.mkdir(exist_ok=True)
    junit = results / "junit.xml"
    junit.unlink(missing_ok=True)
    command = [
        sys.executable,
        "-m",
        "pytest",
        "-q",
        "--basetemp=test-results/pytest",
        "--cov=backend",
        "--cov-report=term:skip-covered",
        "--cov-report=json:reports/coverage.json",
        "-p",
        "no:cacheprovider",
        "--junitxml=" + str(junit),
    ]
    completed = subprocess.run(command, cwd=ROOT)
    cases = ET.parse(junit).getroot().findall(".//testcase") if junit.exists() else []
    failed = sum(case.find("failure") is not None for case in cases)
    errors = sum(case.find("error") is not None for case in cases)
    skipped = sum(case.find("skipped") is not None for case in cases)
    exit_code = completed.returncode or (1 if skipped and os.getenv("RAG_REQUIRE_POSTGRES_TESTS") == "1" else 0)
    digest = hashlib.sha256()
    for folder in ("backend", "tests", "evals", "scripts", "dist"):
        for file in sorted((ROOT / folder).rglob("*")):
            if (
                file.is_file()
                and file.suffix in (".py", ".js", ".cjs", ".css", ".html", ".json", ".jsonl")
                and "__pycache__" not in file.parts
            ):
                digest.update(file.relative_to(ROOT).as_posix().encode())
                digest.update(file.read_bytes())
    data = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "exit_code": exit_code,
        "status": "passed" if exit_code == 0 else "failed",
        "total": len(cases),
        "passed": len(cases) - failed - errors - skipped,
        "failed": failed,
        "errors": errors,
        "skipped": skipped,
        "source_sha256": digest.hexdigest(),
        "python": sys.version.split()[0],
        "source": "test-results/junit.xml",
        "command": "python -m scripts.check",
    }
    (reports / "tests.json").write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    rows = "\n".join(
        f"| {label} | {data[key]} |"
        for key, label in [
            ("total", "Collected"),
            ("passed", "Passed"),
            ("failed", "Failed"),
            ("errors", "Errors"),
            ("skipped", "Skipped"),
        ]
    )
    (reports / "tests.md").write_text(
        "# Latest test run\n\nGenerated by `python -m scripts.check` from pytest JUnit XML; not a live badge.\n\n"
        f"Run: {data['generated_at']} · Status: **{data['status']}** · Python {data['python']}\n\n"
        "| Metric | Count |\n| --- | --- |\n"
        + rows
        + "\n\nSkipped tests have not passed. PostgreSQL integration tests require `RAG_TEST_DATABASE_URL`.\n\n"
        f"Source SHA-256: `{data['source_sha256']}`\n",
        encoding="utf-8",
    )
    print(json.dumps(data))
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
